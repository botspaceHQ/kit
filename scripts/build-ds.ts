// Builds the Design System artifact's files into ds-out/project/:
// tokens.json, README.md, patterns.md, components/bundle.js + bundle.css + index.d.ts,
// components/<Comp>/README.md + preview.html, components/Cover/preview.html, design-system.json.
// Run: node scripts/build-ds.ts
import { execSync } from "node:child_process"
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs"
import { dirname } from "node:path"
import { fileURLToPath } from "node:url"

import { componentDocs, type ComponentDoc } from "../src/docs/component-docs.ts"
import { patternDocs } from "../src/docs/pattern-docs.ts"
import { typeFamilies, typeScale } from "../src/docs/type-scale.ts"
import { parseTokens } from "./tokens.ts"

const root = fileURLToPath(new URL("../", import.meta.url))
const read = (p: string) => readFileSync(root + p, "utf8")
const out = root + "ds-out/project/"
const write = (p: string, text: string) => {
  mkdirSync(dirname(out + p), { recursive: true })
  writeFileSync(out + p, text)
}

const VERSION = JSON.parse(read("package.json")).version as string
const NAMESPACE = "BotSpaceKit"

/* 1. Generated CSS for the bundle: token fallbacks under :where(), the kit CSS with its
      layout sizes moved under :where() too, so tokens.css from the page always wins. */
const tokenCss = read("src/styles/botspace-tokens.css")
mkdirSync(root + "ds/generated", { recursive: true })
writeFileSync(
  root + "ds/generated/fallback.css",
  "/* Generated by scripts/build-ds.ts from src/styles/botspace-tokens.css. Do not edit. */\n" +
    tokenCss.replace(/^:root \{/m, ":where(html) {").replace(/^\.dark \{/m, ':where(html[data-theme="dark"]) {')
)
writeFileSync(
  root + "ds/generated/kit.css",
  "/* Generated by scripts/build-ds.ts from src/styles/botspace-kit.css. Do not edit. */\n" +
    read("src/styles/botspace-kit.css").replace(/^:root \{/m, ":where(html) {")
)

/* 2. The bundle. */
execSync("npx vite build --config vite.ds.config.ts --logLevel warn", { cwd: root, stdio: "inherit" })
const compName = (d: ComponentDoc) => d.name.split(" ")[0]
const header = { format: 4, namespace: NAMESPACE, components: componentDocs.map((d) => ({ name: compName(d) })) }
let bundle = read("ds-dist/bundle.js")
// CommonJS parts of dependencies (use-sync-external-store) keep require("react"): point them at the page's globals.
bundle = bundle.replaceAll('require("react")', "window.React").replaceAll('require("react-dom")', "window.ReactDOM")
if (/\brequire\(/.test(bundle)) throw new Error("bundle.js still calls require()")
// Consumers inline the bundle in a <script>: these two strings would end or escape it.
bundle = bundle.replaceAll("</script", "<\\/script").replaceAll("<!--", "<\\!--")
const css = read("ds-dist/bundle.css")
if (/<\/style/i.test(css)) throw new Error("bundle.css holds </style")

rmSync(out, { recursive: true, force: true })
write("components/bundle.js", `/* @ds-bundle: ${JSON.stringify(header)} */\n${bundle}`)
write("components/bundle.css", css)

/* 3. tokens.json. */
const tokens = parseTokens(tokenCss)
const color = tokens.filter((t) => t.group !== "Radius")
const tokensJson = {
  name: "BotSpace Kit",
  version: 1,
  meta: { source: "botspace-kit", files: ["src/styles/botspace-tokens.css", "src/styles/botspace-kit.css", "src/docs/type-scale.ts"], kit: VERSION },
  color: {
    themes: [
      { id: "light", name: "Light" },
      { id: "dark", name: "Dark" },
    ],
    tokens: color.map((t) => ({ name: t.name, value: { light: t.light, dark: t.dark ?? t.light }, usage: t.note })),
  },
  type: {
    fonts: [],
    families: { sans: typeFamilies.sans.replaceAll("'", '"'), mono: typeFamilies.mono },
    groups: [
      {
        name: "Product",
        family: "sans",
        styles: typeScale
          .filter((s) => s.family === "sans")
          .map((s) => ({ name: s.name, fontSize: s.fontSize, lineHeight: s.lineHeight, fontWeight: s.fontWeight, sample: s.sample, usage: s.usage })),
      },
      {
        name: "Code",
        family: "mono",
        styles: typeScale
          .filter((s) => s.family === "mono")
          .map((s) => ({ name: s.name, fontSize: s.fontSize, lineHeight: s.lineHeight, fontWeight: s.fontWeight, sample: s.sample, usage: s.usage })),
      },
    ],
  },
  spacing: {
    tokens: [
      { name: "header-height", value: "56px", usage: "Every pane header: rail logo row, SubNav title, page header, inbox panes (h-14)." },
      { name: "rail-width", value: "56px", usage: "The icon rail (w-14)." },
      { name: "subnav-width", value: "240px", usage: "The section navigation pane (w-60)." },
      { name: "pane-width", value: "320px", usage: "Inbox list and details panes (w-80)." },
      { name: "space-2", value: "8px", usage: "Gap between buttons and chips in a row (gap-2)." },
      { name: "space-4", value: "16px", usage: "Page padding and gap under 768 px. Card inner spacing (p-4, gap-4)." },
      { name: "space-6", value: "24px", usage: "Page padding and gap from 768 px (md:p-6, md:gap-6)." },
      { name: "content-max", value: "1400px", usage: "Widest content column on list, report and home pages." },
    ],
  },
  radius: {
    tokens: [
      { name: "radius", value: "8px", usage: "The base (--radius). Inputs, selects, menus, tables." },
      { name: "radius-sm", value: "4.8px", usage: "Small marks inside controls." },
      { name: "radius-md", value: "6.4px", usage: "Navigation items and rail buttons." },
      { name: "radius-xl", value: "11.2px", usage: "Cards and settings tiles." },
      { name: "radius-chip", value: "6px", usage: "Badge and StatusBadge, by the [data-slot=badge] rule." },
      { name: "radius-pill", value: "9999px", usage: "Buttons, tabs, segmented controls and avatars, by the [data-slot] rules." },
    ],
  },
}
write("tokens.json", JSON.stringify(tokensJson, null, 2) + "\n")

/* 4. Brand book and the patterns section. */
write("README.md", read("ds/README.md"))
write(
  "patterns.md",
  "# Patterns\n\nFour page patterns cover the product. Build a new page from the nearest one.\n\n" +
    patternDocs
      .map(
        (p) =>
          `## ${p.name}\n\n${p.summary}\n\n${p.anatomy.map(([a, b], i) => `${i + 1}. **${a}.** ${b}`).join("\n")}\n\n` +
          `Rules:\n\n${p.rules.map((r) => `- ${r}`).join("\n")}\n\nBuilt from: ${p.uses
            .map((id) => componentDocs.find((d) => d.id === id))
            .filter(Boolean)
            .map((d) => compName(d!))
            .join(", ")}.\n`
      )
      .join("\n")
)

/* 5. One card per component. */
const esc = (s: string) => s.replaceAll('"', "'")
for (const d of componentDocs) {
  const name = compName(d)
  const install = d.group === "Stock shadcn" ? `npx shadcn@latest add ${d.item}` : `npx shadcn@latest add @botspace/${d.item}`
  write(
    `components/${name}/README.md`,
    `${d.summary}\n\n${d.use}\n\n## Install\n\n\`\`\`bash\n${install}\n\`\`\`\n\nSource: \`${d.file}\`${d.group === "Stock shadcn" ? " (stock shadcn, not forked)" : ""}.\n\n` +
      `## Usage\n\n\`\`\`tsx\n${d.code}\n\`\`\`\n\n## What you provide\n\n| Prop | Type | What it does |\n| --- | --- | --- |\n` +
      d.props.map((p) => `| \`${p.name}\` | \`${p.type.replaceAll("|", "\\|")}\`${p.default ? ` (default ${p.default})` : ""} | ${p.description} |`).join("\n") +
      `\n\n## Do\n\n${d.dos.map((x) => `- ${x}`).join("\n")}\n\n## Don't\n\n${d.donts.map((x) => `- ${x}`).join("\n")}\n`
  )
  write(
    `components/${name}/preview.html`,
    `<!-- @dsCard group="${esc(d.group)}" height=${(d.height ?? 160) + 32}${d.width ? ` width=${d.width}` : ""} subtitle="${esc(d.summary)}" -->\n` +
      `<div id="root" style="padding:16px"></div>\n` +
      `<script>window.${NAMESPACE}.mount(document.getElementById("root"), ${JSON.stringify(d.id)})</script>\n`
  )
}

/* 6. Types, as documentation. */
const ident = (s: string) => (/^[A-Za-z_$][\w$]*$/.test(s) ? s : JSON.stringify(s))
write(
  "components/index.d.ts",
  `// BotSpace Kit ${VERSION}. Documentation types: window.${NAMESPACE}.<Component>. React 18 or 19.\n\n` +
    componentDocs
      .map(
        (d) =>
          `/** ${d.summary} */\nexport interface ${compName(d)}Props {\n` +
          d.props.map((p) => `  /** ${p.description}${p.default ? ` Default ${p.default}.` : ""} */\n  ${ident(p.name)}?: ${p.type.includes("=>") || p.type.includes("{") ? "unknown /* " + p.type.replaceAll("*/", "") + " */" : p.type};`).join("\n") +
          `\n}\n`
      )
      .join("\n") +
    `\n/** Render a component's demo into an element. Preview cards call it. */\nexport declare function mount(el: HTMLElement, id: string): void\n`
)

/* 7. The cover. */
write("components/Cover/preview.html", read("ds/cover.html"))

/* 8. Assets already uploaded to the artifact, and the index. The index goes last in the publish call. */
const assets = JSON.parse(read("ds/assets.json"))
write("assets/Logos/README.md", read("ds/assets/Logos/README.md"))
const now = new Date().toISOString()
write(
  "design-system.json",
  JSON.stringify(
    {
      v: 3,
      layout: "files",
      createdOnFiles: { v: 1, at: now },
      title: "BotSpace Kit",
      namespace: NAMESPACE,
      libraries: [
        { name: "react", version: "18" },
        { name: "react-dom", version: "18" },
      ],
      sections: {},
      groups: assets.groups,
      assetGroups: assets.assetGroups,
      blobs: {},
      docs: { sections: [] },
      lastChange: { by: "Mayur", at: now, via: "Claude Code", note: `BotSpace Kit ${VERSION}: tokens, ${componentDocs.length} components, 4 patterns.` },
    },
    null,
    2
  ) + "\n"
)
console.log(`ds-out/project: ${componentDocs.length} components, ${color.length} colours, bundle ${(bundle.length / 1024).toFixed(0)} KB, css ${(css.length / 1024).toFixed(0)} KB`)

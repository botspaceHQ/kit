// Builds the @botspacehq/kit npm package into dist/:
// src/index.ts (generated: every file in components/ui and components/kit, the theme provider, cn),
// one ES module per source file, .d.ts types with "@/" rewritten to relative paths, and styles.css.
// Apps import "@botspacehq/kit/styles.css" and add `@source "<path to>/node_modules/@botspacehq/kit/dist";`.
// Run: node scripts/build-lib.ts
import { execSync } from "node:child_process"
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs"
import { dirname, join, relative } from "node:path"
import { fileURLToPath } from "node:url"

const root = fileURLToPath(new URL("../", import.meta.url))
const read = (p: string) => readFileSync(root + p, "utf8")
const run = (cmd: string) => execSync(cmd, { cwd: root, stdio: "inherit" })

/* 1. The entry. Stock primitives first, then the kit blocks. */
const modules = (dir: string) =>
  readdirSync(root + "src/" + dir)
    .filter((f) => f.endsWith(".tsx") || f.endsWith(".ts"))
    .sort()
    .map((f) => `./${dir}/${f.replace(/\.tsx?$/, "")}`)
const entry = [
  "// Generated by scripts/build-lib.ts. Do not edit.",
  ...modules("components/ui").map((m) => `export * from "${m}"`),
  ...modules("components/kit").map((m) => `export * from "${m}"`),
  `export * from "./components/theme-provider"`,
  `export { cn } from "./lib/utils"`,
  "",
].join("\n")
writeFileSync(root + "src/index.ts", entry)

/* 2. JavaScript. */
run("npx vite build --config vite.lib.config.ts --logLevel warn")

/* 3. Types. tsc keeps the "@/" alias in .d.ts files; apps cannot resolve it, so make it relative. */
run("npx tsc -p tsconfig.lib.json")
const walk = (dir: string): string[] =>
  readdirSync(dir).flatMap((f) => (statSync(join(dir, f)).isDirectory() ? walk(join(dir, f)) : [join(dir, f)]))
for (const file of walk(root + "dist").filter((f) => f.endsWith(".d.ts"))) {
  const text = readFileSync(file, "utf8")
  const fixed = text.replace(/(from |import\()(["'])@\/([^"']+)\2/g, (_, pre, q, path) => {
    let rel = relative(dirname(file), join(root, "dist", path))
    if (!rel.startsWith(".")) rel = "./" + rel
    return `${pre}${q}${rel}${q}`
  })
  if (fixed !== text) writeFileSync(file, fixed)
}

/* 4. styles.css: the shadcn base (variants and animations), the tokens, the kit theme map. The app's
      Tailwind compiles it, so it stays source CSS. tw-animate-css is a dependency of the package. */
const version = JSON.parse(read("node_modules/shadcn/package.json")).version as string
const shadcnCss = read("node_modules/shadcn/dist/tailwind.css")
writeFileSync(
  root + "dist/styles.css",
  [
    `/* @botspacehq/kit ${JSON.parse(read("package.json")).version}. Import after "tailwindcss". */`,
    `@import "tw-animate-css";`,
    "",
    `/* ---- shadcn ${version} base (shadcn/tailwind.css, MIT) ---- */`,
    shadcnCss,
    "/* ---- src/styles/botspace-tokens.css ---- */",
    read("src/styles/botspace-tokens.css"),
    "/* ---- src/styles/botspace-kit.css ---- */",
    read("src/styles/botspace-kit.css"),
    "@custom-variant dark (&:is(.dark *));",
    "",
  ].join("\n")
)
